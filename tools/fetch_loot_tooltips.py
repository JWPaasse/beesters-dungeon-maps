#!/usr/bin/env python3
"""Write the tooltips of the bosses' loot for the addon (BeestersDungeonMaps/Data/LootTooltips.lua).

    python3 tools/fetch_loot_tooltips.py [--refresh | --offline]

For some items the game server never sends the details, so the game's own tooltip stays on
"Retrieving item information". For those the addon shows this copy instead, taken from:
1. the WoW Forever client's own item tables (tools/game_item_tooltips.json, from
   tools/build_game_tooltips.py): real WoW Forever values for the items Forever added or changed;
2. else the Classic database's item stats (tools/classic_item_tooltips.json, from
   tools/build_classic_tooltips.py), marked as classic values.
Wowhead's tooltips are off (USE_WOWHEAD below): Wowhead's terms don't allow copying their data.
"""
import datetime
import json
import re
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOSSES = ROOT / "BeestersDungeonMaps" / "Data" / "Bosses.lua"
CACHE = ROOT / "tools" / "loot_tooltips.json"
OUT = ROOT / "BeestersDungeonMaps" / "Data" / "LootTooltips.lua"
sys.path.insert(0, str(ROOT / "tools"))
from build_data import lua_str  # noqa: E402
from wowhead_tooltip import tooltip_lines  # noqa: E402

URL = "https://nether.wowhead.com/forever/tooltip/item/{}"

# Off until Wowhead has said the addon may include their tooltips: then nothing is fetched from
# Wowhead and every tooltip is built from the Classic database's item stats (GPL). To switch it on
# (only with Wowhead's permission), set this to True; the next refresh fetches them again.
USE_WOWHEAD = False


def fetch(item_id):
    req = urllib.request.Request(URL.format(item_id), headers={"User-Agent": "BeestersDungeonMaps data build (GitHub Actions)"})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def main():
    refresh = "--refresh" in sys.argv
    loot = BOSSES.read_text(encoding="utf-8").split("ns.BossLoot = {")[1]
    ids = sorted({int(i) for body in re.findall(r"^    \[\d+\] = \{([\d,]+)\}", loot, re.M) for i in body.split(",")})
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() and not refresh else {"items": {}, "missing": []}
    if not USE_WOWHEAD:
        cache = {"items": {}, "missing": []}
    today = datetime.date.today()
    checked = cache.setdefault("checked", {})
    for key in list(cache["items"]) + [str(i) for i in cache["missing"]]:
        checked.setdefault(key, today.isoformat())  # files from before dates were kept

    def due(key):
        if key not in checked:
            return True
        age = (today - datetime.date.fromisoformat(checked[key])).days
        return age >= (30 if key in cache["items"] else 7)

    fetched = 0
    for item_id in ids:
        key = str(item_id)
        if not USE_WOWHEAD or "--offline" in sys.argv or not due(key):
            continue
        data = fetch(item_id)
        fetched += 1
        checked[key] = today.isoformat()
        if data and data.get("tooltip"):
            cache["items"][key] = tooltip_lines(data["tooltip"])
            if item_id in cache["missing"]:
                cache["missing"].remove(item_id)
        elif key not in cache["items"] and item_id not in cache["missing"]:
            cache["missing"].append(item_id)
        time.sleep(0.25)
    cache["_source"] = "Wowhead's WoW Forever item tooltips (nether.wowhead.com)."
    cache["missing"] = sorted(set(cache["missing"]))
    if USE_WOWHEAD:
        CACHE.write_text(json.dumps(cache, indent=0, ensure_ascii=False) + "\n", encoding="utf-8")
    elif CACHE.exists():
        CACHE.unlink()  # no copy of Wowhead's tooltips kept in the project

    out = [
        "-- AUTO GENERATED by tools/fetch_loot_tooltips.py. Do not edit by hand.",
        "-- Item tooltips: the WoW Forever client's own item tables (tools/game_item_tooltips.json), else the",
        "-- CMaNGOS Classic database's item stats (GPL-3.0).",
        "-- Shown only when the game hasn't got the item.",
        "local _, ns = ...",
        "",
        "-- [itemID] = { line, ... } (game colour codes; a tab separates left and right text)",
        "ns.LootTooltips = {",
    ]
    classic_file = ROOT / "tools" / "classic_item_tooltips.json"
    classic = json.loads(classic_file.read_text(encoding="utf-8"))["items"] if classic_file.exists() else {}
    game_file = ROOT / "tools" / "game_item_tooltips.json"
    game = json.loads(game_file.read_text(encoding="utf-8"))["items"] if game_file.exists() else {}
    for item_id in ids:
        lines = cache["items"].get(str(item_id)) or game.get(str(item_id)) or classic.get(str(item_id))
        if lines:
            out.append("    [%d] = {%s}," % (item_id, ",".join(lua_str(l).replace("\t", "\\t") for l in lines)))
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    from_game = sum(1 for i in ids if str(i) not in cache["items"] and str(i) in game)
    from_classic = sum(1 for i in ids if str(i) not in cache["items"] and str(i) not in game and str(i) in classic)
    print(f"Fetched {fetched}; Wowhead tooltips for {sum(1 for i in ids if str(i) in cache['items'])} of {len(ids)} loot items, "
          f"game ones for {from_game}, classic ones for {from_classic} more; {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
