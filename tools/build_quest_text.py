#!/usr/bin/env python3
"""Build BeestersDungeonMaps/Data/QuestText.lua: the full text and rewards of the dungeon quests.

    python3 tools/build_quest_text.py [ClassicDB.sql.gz]

QuestieDB only has each quest's short objective line. The quest's own description, its
objectives with counts, and its rewards (fixed items, choice items, money) come from the
CMaNGOS Classic database (GPL-3.0, https://github.com/cmangos/classic-db). Without a file
argument the latest Full_DB dump is downloaded. Only quests the addon lists (Data/Quests.lua)
are kept. Quests new in WoW Forever aren't in the Classic database; those keep QuestieDB's line.
"""
import gzip
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "BeestersDungeonMaps" / "Data" / "QuestText.lua"
QUESTS = ROOT / "BeestersDungeonMaps" / "Data" / "Quests.lua"
REPO = "https://raw.githubusercontent.com/cmangos/classic-db/master/Full_DB/"


def download():
    # The dump's file name changes with each database revision; read it from the README links
    # isn't possible, so try the GitHub tree page through the API-less raw listing of .gitignore.
    listing = urllib.request.urlopen("https://github.com/cmangos/classic-db/tree/master/Full_DB").read().decode()
    name = re.search(r"ClassicDB_[\w.]+\.sql\.gz", listing).group(0)
    print("Downloading", name)
    return urllib.request.urlopen(REPO + name).read()


def parse_values(blob):
    """Split a MySQL VALUES (...),(...) list into rows of Python values."""
    rows, row, i, n = [], None, 0, len(blob)
    while i < n:
        c = blob[i]
        if c == "(" and row is None:
            row, i = [], i + 1
            continue
        if row is None:
            i += 1
            continue
        if c == "'":
            j, buf = i + 1, []
            while True:
                d = blob[j]
                if d == "\\":
                    nxt = blob[j + 1]
                    buf.append({"n": "\n", "r": "\r", "t": "\t", "0": "\0"}.get(nxt, nxt))
                    j += 2
                elif d == "'":
                    if j + 1 < n and blob[j + 1] == "'":
                        buf.append("'")
                        j += 2
                    else:
                        break
                else:
                    buf.append(d)
                    j += 1
            row.append("".join(buf))
            i = j + 1
        elif c in ",\n\r\t ":
            i += 1
        elif c == ")":
            rows.append(row)
            row, i = None, i + 1
        else:
            m = re.match(r"-?[\d.]+|NULL", blob[i:i + 30])
            token = m.group(0)
            row.append(None if token == "NULL" else (float(token) if "." in token else int(token)))
            i += len(token)
    return rows


def lua_str(s):
    s = (s or "").replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n")
    return '"' + s + '"'


def main():
    raw = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else download()
    sql = gzip.decompress(raw).decode("utf-8", errors="replace")
    create = re.search(r"CREATE TABLE `quest_template` \((.*?)\) ENGINE", sql, re.S).group(1)
    cols = re.findall(r"^\s*`(\w+)`", create, re.M)
    rows = []
    for m in re.finditer(r"INSERT INTO `quest_template` VALUES (.*?);\n", sql, re.S):
        rows += parse_values(m.group(1))
    wanted = {int(q) for q in re.findall(r"^\s*\[(\d+)\] = \{\"", QUESTS.read_text(encoding="utf-8").split("ns.Quests = {")[1].split("ns.NPCs")[0], re.M)}

    out = [
        "-- AUTO GENERATED by tools/build_quest_text.py. Do not edit by hand.",
        "-- Quest text and rewards: CMaNGOS Classic-DB (GPL-3.0), https://github.com/cmangos/classic-db",
        "-- World of Warcraft quest text is (c) Blizzard Entertainment.",
        "local _, ns = ...",
        "",
        "-- [questID] = { description, objectives, { {itemID, count}... } choice rewards,",
        "--   { {itemID, count}... } fixed rewards, money (copper), { {itemOrCreatureID, count, isItem}... } goals }",
        "ns.QuestText = {",
    ]
    found = 0
    for r in rows:
        q = dict(zip(cols, r))
        qid = q["entry"]
        if qid not in wanted:
            continue
        found += 1
        choice = [(q[f"RewChoiceItemId{i}"], q[f"RewChoiceItemCount{i}"]) for i in range(1, 7) if q[f"RewChoiceItemId{i}"]]
        fixed = [(q[f"RewItemId{i}"], q[f"RewItemCount{i}"]) for i in range(1, 5) if q[f"RewItemId{i}"]]
        goals = [(q[f"ReqItemId{i}"], q[f"ReqItemCount{i}"], True) for i in range(1, 5) if q[f"ReqItemId{i}"]]
        goals += [(abs(q[f"ReqCreatureOrGOId{i}"]), q[f"ReqCreatureOrGOCount{i}"], False)
                  for i in range(1, 5) if q[f"ReqCreatureOrGOId{i}"]]
        money = max(q["RewOrReqMoney"] or 0, 0)
        pairs = lambda xs: "{" + ",".join("{%d,%d}" % (a, b) for a, b in xs) + "}"
        gl = "{" + ",".join("{%d,%d,%s}" % (a, b, "true" if c else "false") for a, b, c in goals) + "}"
        out.append(f"    [{qid}] = {{{lua_str(q['Details'])},{lua_str(q['Objectives'])},{pairs(choice)},{pairs(fixed)},{money},{gl}}},")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: text for {found} of {len(wanted)} quests ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
