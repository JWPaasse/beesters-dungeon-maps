#!/usr/bin/env python3
"""Build the dungeon map data and textures.

    python3 tools/build_maps.py

- Old dungeons: the classic dungeon map tiles that still ship in the WoW Forever client
  (tools/dungeon_maps.json). The addon only refers to them by file ID; nothing is copied.
- New Forever dungeons: Santiago Reyes's maps (tools/art/santiago/*.webp), used with his
  permission, watermark kept. Converted to BLP textures in BeestersDungeonMaps/Media/Maps.
- Boss positions: the retail Dungeon Journal's positions on those same maps
  (tools/journal_positions.json), plus Cataclysm Classic's journal for the original bosses of
  dungeons that were rebuilt later (tools/journal_positions_cata.json, made by
  tools/fetch_cata_positions.py). Matched to the game's own boss list in the addon.

Writes BeestersDungeonMaps/Data/Maps.lua.
"""
import json
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from blp import save_blp  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ADDON = ROOT / "BeestersDungeonMaps"
ART = ROOT / "tools" / "art" / "santiago"
MEDIA = ADDON / "Media" / "Maps"

# Santiago's maps: instance key -> floor names, in floor order (file <key><n>.webp).
SANTIAGO = {
    "hot": ["Hall of Thanes"],
    "rol": ["Ruins of Lordaeron"],
    "exc": ["Excavation Site: Wetlands"],
    "dal": ["City of Dalaran", "The Underbelly"],
}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_santiago():
    """Each map becomes two textures: 1024x1024 (left) and 512x1024 (right), shown as 1536x1024."""
    MEDIA.mkdir(parents=True, exist_ok=True)
    maps = {}
    for key, names in SANTIAGO.items():
        floors = []
        for n, name in enumerate(names, 1):
            src = ART / f"{key}{n}.webp"
            if not src.exists():
                print(f"missing {src}, skipped")
                continue
            img = Image.open(src).convert("RGB").resize((1536, 1024), Image.LANCZOS)
            save_blp(img.crop((0, 0, 1024, 1024)), MEDIA / f"{key}{n}a.blp")
            save_blp(img.crop((1024, 0, 1536, 1024)), MEDIA / f"{key}{n}b.blp")
            floors.append(name)
        maps[key] = floors
    return maps


def main():
    tiles = json.loads((ROOT / "tools" / "dungeon_maps.json").read_text(encoding="utf-8"))
    journal = json.loads((ROOT / "tools" / "journal_positions.json").read_text(encoding="utf-8"))["bosses"]
    # Cataclysm's journal fills in the original bosses of dungeons that were rebuilt later.
    cata_file = ROOT / "tools" / "journal_positions_cata.json"
    if cata_file.exists():
        def norm(name):
            return "".join(ch for ch in name.lower() if ch.isalpha())
        known = {(b[0].split("|")[0], norm(b[2])) for b in journal} | {(b[0].split("|")[0], b[1]) for b in journal}
        for b in json.loads(cata_file.read_text(encoding="utf-8"))["bosses"]:
            dungeon = b[0].split("|")[0]
            if (dungeon, norm(b[2])) not in known and (dungeon, b[1]) not in known:
                journal.append(b)
    santiago = build_santiago()

    # Which instance key and floor does each journal map floor belong to?
    floor_owner = {}
    for key in tiles["maps"]:
        for n in range(1, len(tiles["maps"][key]) + 1):
            floor_owner[f"{key}|{n}"] = (key, n)
    for wing, (base, wing_floors) in tiles["wings"].items():
        for i, n in enumerate(wing_floors, 1):
            floor_owner[f"{base}|{n}"] = (wing, i)

    lines = [
        "-- AUTO GENERATED by tools/build_maps.py. Do not edit by hand.",
        "-- Old dungeons: the classic dungeon map tiles that still ship in the WoW Forever client (file IDs).",
        "-- New dungeons: maps by Santiago Reyes, used with permission.",
        "-- Boss positions: the retail Dungeon Journal's positions on the same maps.",
        "local _, ns = ...",
        "",
        "-- [instanceKey] = { floors = { { tiles = {12 file IDs} } or { texture = path, name = ... } }, artist = ... }",
        "ns.DungeonMaps = {",
    ]

    def tile_floors(key, floor_numbers=None):
        floors = tiles["maps"][key]
        picked = [floors[n - 1] for n in floor_numbers] if floor_numbers else floors
        return ", ".join("{ tiles = {" + ",".join(map(str, f)) + "} }" for f in picked)

    for key in sorted(tiles["maps"]):
        if key == "diremaul":
            continue
        lines.append(f"    [{lua_str(key)}] = {{ floors = {{ {tile_floors(key)} }} }},")
    for wing, (base, wing_floors) in sorted(tiles["wings"].items()):
        lines.append(f"    [{lua_str(wing)}] = {{ floors = {{ {tile_floors(base, wing_floors)} }} }},")
    for key, names in sorted(santiago.items()):
        parts = []
        for n, name in enumerate(names, 1):
            tex = f"Interface\\\\AddOns\\\\BeestersDungeonMaps\\\\Media\\\\Maps\\\\{key}{n}"
            parts.append(f'{{ texture = "{tex}", name = {lua_str(name)} }}')
        lines.append(f'    [{lua_str(key)}] = {{ floors = {{ {", ".join(parts)} }}, artist = "Santiago Reyes" }},')
    lines.append("}")
    lines.append("")
    lines.append("-- [instanceKey] = { { floor, x, y, encounterID, name }, ... }")
    lines.append("ns.BossPositions = {")
    by_key = {}
    for floor_key, enc, name, x, y in journal:
        owner = floor_owner.get(floor_key)
        if owner:
            key, floor = owner
            by_key.setdefault(key, []).append(f"{{{floor},{x},{y},{enc},{lua_str(name)}}}")
    for key in sorted(by_key):
        lines.append(f"    [{lua_str(key)}] = {{ {', '.join(by_key[key])} }},")
    lines.append("}")
    lines.append("")
    lines.append("-- [instance map ID from GetInstanceInfo()] = instanceKey (Dire Maul: all wings share one ID)")
    lines.append("ns.InstanceByMap = {")
    instances = json.loads((ROOT / "tools" / "instances.json").read_text(encoding="utf-8"))["instances"]
    seen = {}
    for info in instances.values():
        if info.get("map") and info["map"] not in seen:
            seen[info["map"]] = info["key"]
    for map_id, key in sorted(seen.items()):
        lines.append(f"    [{map_id}] = {lua_str(key)},")
    lines.append("}")
    (ADDON / "Data" / "Maps.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Maps: {len(tiles['maps']) - 1 + len(tiles['wings'])} classic, {len(santiago)} by Santiago Reyes; "
          f"boss positions for {len(by_key)} instances")


if __name__ == "__main__":
    main()
