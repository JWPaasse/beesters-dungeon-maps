#!/usr/bin/env python3
"""Build Beester's Dungeon Maps data files from QuestieDB (GPL-3.0).

Usage:
    python3 tools/build_data.py /path/to/QuestieDB

Reads QuestieDB's Forever support data and writes BeestersDungeonMaps/Data/Entrances.lua.
Only instances listed in tools/instances.json are included.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "BeestersDungeonMaps" / "Data" / "Entrances.lua"


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse_area_to_uimap(path):
    """Parse '[areaId] = uiMapId,' lines from areaIdToUiMapId.lua (base table and overrides)."""
    mapping = {}
    for m in re.finditer(r"^\s*\[(\d+)\]\s*=\s*(\d+)\s*,", path.read_text(encoding="utf-8"), re.M):
        area, ui = int(m.group(1)), int(m.group(2))
        mapping.setdefault(area, ui)
    return mapping


def parse_dungeons(path):
    """Parse the main dungeons table: [areaId] = {"Name", alt, parent, {{zone, x, y}, ...}}."""
    text = path.read_text(encoding="utf-8")
    body = text.split("local dungeons = {", 1)[1].split("\n}\n", 1)[0]
    entries = {}
    line_re = re.compile(r"^\s*\[(\d+)\]\s*=\s*\{\"([^\"]+)\",(nil|\{[^}]*\}),(\d+),\{(.*)\}\},?", re.M)
    point_re = re.compile(r"\{\s*(\d+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\}")
    for m in line_re.finditer(body):
        area = int(m.group(1))
        alternates = [int(a) for a in re.findall(r"\d+", m.group(3))] if m.group(3) != "nil" else []
        points = [(int(z), float(x), float(y)) for z, x, y in point_re.findall(m.group(5))]
        entries[area] = {"name": m.group(2), "alternates": alternates, "points": points}
    return entries


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    qdb = Path(sys.argv[1])
    zones = qdb / "support" / "Forever" / "Zones"
    area_to_ui = parse_area_to_uimap(zones / "areaIdToUiMapId.lua")
    dungeons = parse_dungeons(zones / "dungeons.lua")
    curated = json.loads((ROOT / "tools" / "instances.json").read_text(encoding="utf-8"))["instances"]

    try:
        rev = subprocess.check_output(["git", "-C", str(qdb), "rev-parse", "--short", "HEAD"], text=True).strip()
    except Exception:
        rev = "unknown"

    instances, entrances, problems = [], {}, []
    for area_str, info in curated.items():
        area = int(area_str)
        src = dungeons.get(area)
        if not src:
            problems.append(f"{info['name']}: AreaID {area} not found in QuestieDB")
            continue
        instances.append((info, area))
        for zone, x, y in src["points"]:
            ui = area_to_ui.get(zone)
            if not ui:
                problems.append(f"{info['name']}: no UiMapID for zone AreaID {zone}")
                continue
            # Several instances can share one door (Blackrock Mountain). Group them.
            spot = (ui, round(x, 1), round(y, 1))
            entrances.setdefault(spot, []).append(info["key"])

    lines = [
        "-- AUTO GENERATED by tools/build_data.py. Do not edit by hand.",
        f"-- Entrance coordinates: QuestieDB (GPL-3.0), revision {rev}, support/Forever/Zones/dungeons.lua.",
        "-- Instance list and level ranges: tools/instances.json.",
        "local _, ns = ...",
        "",
        "ns.dataVersion = " + lua_str(rev),
        "",
        "-- [key] = { name, kind, levels, isNew, note, size }",
        "ns.Instances = {",
    ]
    for info, area in sorted(instances, key=lambda t: (int(t[0]["levels"].split("-")[0]), t[0]["name"])):
        parts = [
            f"name = {lua_str(info['name'])}",
            f"kind = {lua_str(info['kind'])}",
            f"levels = {lua_str(info['levels'].replace('-', '–'))}",
            f"areaId = {area}",
        ]
        if info.get("new"):
            parts.append("isNew = true")
        if info.get("note"):
            parts.append(f"note = {lua_str(info['note'])}")
        if info.get("size"):
            parts.append(f"size = {lua_str(info['size'])}")
        lines.append(f"    [{lua_str(info['key'])}] = {{ {', '.join(parts)} }},")
    lines += ["}", "", "-- [uiMapID] = { { x, y, { instanceKey, ... } }, ... }  (x and y are 0-1)", "ns.Entrances = {"]
    by_map = {}
    for (ui, x, y), keys in entrances.items():
        by_map.setdefault(ui, []).append((x, y, keys))
    for ui in sorted(by_map):
        pins = ", ".join(
            "{ %.4f, %.4f, { %s } }" % (x / 100, y / 100, ", ".join(lua_str(k) for k in keys))
            for x, y, keys in sorted(by_map[ui])
        )
        lines.append(f"    [{ui}] = {{ {pins} }},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Wrote {OUT.relative_to(ROOT)}: {len(instances)} instances, {len(entrances)} entrance points, QuestieDB {rev}")
    for p in problems:
        print("WARNING:", p)


if __name__ == "__main__":
    main()
