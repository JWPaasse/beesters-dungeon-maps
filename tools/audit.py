#!/usr/bin/env python3
"""Audit the addon's data: per instance, which bosses have a map position (and from where),
how much loot each boss shows, and which loot items lack a tooltip. Writes docs/AUDIT.md.

    python3 tools/audit.py

"Shown" loot is what the addon lists: Bind on Pickup, Uncommon or better (Data/Bosses.lua,
ns.LootItems). Items without item data are counted as "unknown" (the game fills them in).
A tooltip counts as covered when Data/LootTooltips.lua has WoW Forever's tooltip for it.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "BeestersDungeonMaps" / "Data"
OUT = ROOT / "docs" / "AUDIT.md"


def lua_section(text, name):
    return text.split(f"ns.{name} = {{")[1].split("\n}")[0]


def main():
    bosses_lua = (DATA / "Bosses.lua").read_text(encoding="utf-8")
    maps_lua = (DATA / "Maps.lua").read_text(encoding="utf-8")
    entr = (DATA / "Entrances.lua").read_text(encoding="utf-8")
    names = dict(re.findall(r'\["(\w+)"\] = \{ name = "([^"]+)"', entr))
    bosses = {k: re.findall(r'\{(\d+),"((?:[^"\\]|\\.)*)",(\w+)[,}]', body)
              for k, body in re.findall(r'\["(\w+)"\] = \{ (.*?) \},\n', lua_section(bosses_lua, "Bosses"))}
    positions = {k: re.findall(r'\{(\d+),[\d.]+,[\d.]+,(\d+),"((?:[^"\\]|\\.)*)"\}', body)
                 for k, body in re.findall(r'\["(\w+)"\] = \{ (\{.*?\}) \},\n', lua_section(maps_lua, "BossPositions"))}
    loot = {int(n): [int(i) for i in v.split(",")] for n, v in re.findall(r"^    \[(\d+)\] = \{([\d,]+)\}", lua_section(bosses_lua, "BossLoot"), re.M)}
    items = {int(i): (n, int(q), int(b)) for i, n, q, b in re.findall(r'^    \[(\d+)\] = \{"((?:[^"\\]|\\.)*)",(\d+),(\d+)\}', lua_section(bosses_lua, "LootItems"), re.M)}
    tips = set(int(i) for i in re.findall(r"^    \[(\d+)\]", (DATA / "LootTooltips.lua").read_text(encoding="utf-8"), re.M))

    # Where each position came from (the tools/*.json sources, in build_maps.py's order).
    source = {}
    dm_lua = (ROOT / "BeestersDungeonMaps" / "DungeonMap.lua").read_text(encoding="utf-8")
    aliases = dict(re.findall(r'(\w+) = "(\w+)"', dm_lua.split("local NAME_ALIASES = {")[1].split("\n}")[0]))
    norm = lambda s: (lambda n: aliases.get(n, n))(re.sub(r"[^a-z]", "", s.lower()))
    for fname, tag in [("journal_positions.json", "journal"), ("journal_positions_cata.json", "journal"),
                       ("wowhead_positions.json", "wowhead"), ("placed_positions.json", "placed in game"),
                       ("spawn_positions.json", "spawn point")]:
        f = ROOT / "tools" / fname
        if not f.exists():
            continue
        for b in json.loads(f.read_text(encoding="utf-8"))["bosses"]:
            key = (b[0].split("|")[0], norm(b[2]))
            source.setdefault(key, tag)
            if b[1]:
                source.setdefault((b[0].split("|")[0], b[1]), tag)
    confirmed = json.loads((ROOT / "tools" / "confirmed_positions.json").read_text(encoding="utf-8"))["confirmed"] \
        if (ROOT / "tools" / "confirmed_positions.json").exists() else {}

    lines = ["# Data audit", "", "Generated by `tools/audit.py`. Per instance: bosses with a map position (and its source),",
             "loot the addon shows (Bind on Pickup, Uncommon+), and loot without WoW Forever's tooltip in the addon.", ""]
    totals = dict(bosses=0, placed=0, confirmed=0, noloot=0, shown=0, notip=0)
    summary = ["| Instance | Bosses placed | Confirmed | Bosses without loot | Loot shown | Without tooltip |", "|---|---|---|---|---|---|"]
    detail = []
    for key in sorted(bosses, key=lambda k: names.get(k, k)):
        blist = bosses[key]
        pos = positions.get(key, [])
        by_enc = {int(e) for _, e, _ in pos if int(e)}
        by_name = {norm(n) for _, _, n in pos}
        conf = set(confirmed.get(key, []))
        rows, placed, noloot, shown_total, notip_total = [], 0, 0, 0, 0
        for enc, name, nid in blist:
            has_pos = int(enc) in by_enc or norm(name) in by_name
            src = source.get((key, int(enc))) or source.get((key, norm(name))) or ("—" if not has_pos else "?")
            placed += has_pos
            ids = loot.get(int(nid), []) if nid != "nil" else []
            shown = [i for i in ids if i in items and items[i][1] >= 2 and items[i][2] == 1]
            unknown = [i for i in ids if i not in items]
            notip = [i for i in shown + unknown if i not in tips]
            noloot += not (shown or unknown)
            shown_total += len(shown) + len(unknown)
            notip_total += len(notip)
            rows.append(f"| {name} | {'yes' if has_pos else '**no**'} | {src} | {'yes' if name in conf else ''} | "
                        f"{len(shown)}{f' (+{len(unknown)} unknown)' if unknown else ''} | {len(notip)} |")
        n = len(blist)
        totals["bosses"] += n; totals["placed"] += placed; totals["noloot"] += noloot
        totals["shown"] += shown_total; totals["notip"] += notip_total; totals["confirmed"] += len(conf)
        summary.append(f"| {names.get(key, key)} | {placed}/{n} | {len(conf)}/{n} | {noloot} | {shown_total} | {notip_total} |")
        detail += [f"## {names.get(key, key)}", "", "| Boss | Position | Source | Confirmed | Loot shown | Without tooltip |",
                   "|---|---|---|---|---|---|"] + rows + [""]
    summary.append(f"| **All** | {totals['placed']}/{totals['bosses']} | {totals['confirmed']}/{totals['bosses']} | "
                   f"{totals['noloot']} | {totals['shown']} | {totals['notip']} |")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines + summary + [""] + detail) + "\n", encoding="utf-8")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
